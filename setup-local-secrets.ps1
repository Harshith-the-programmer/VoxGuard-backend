$ErrorActionPreference = 'Stop'

Write-Host "VoxGuard local configuration" -ForegroundColor Cyan
Write-Host "This script saves environment variables for your Windows user and current PowerShell session."
Write-Host "Do not paste any passwords or JWT secrets into chat or source code."
Write-Host ""

# Application connection settings (matches the database already used by VoxGuard).
$dbUrl = 'jdbc:mysql://localhost:3306/voice_clone_db'
$dbUsername = 'voiceclone_app'
[Environment]::SetEnvironmentVariable('DB_URL', $dbUrl, 'User')
[Environment]::SetEnvironmentVariable('DB_USERNAME', $dbUsername, 'User')
$env:DB_URL = $dbUrl
$env:DB_USERNAME = $dbUsername

# Read the password generated by MySQL without echoing it to the terminal.
$securePassword = Read-Host 'Paste the generated password for MySQL user voiceclone_app' -AsSecureString
if ($securePassword.Length -eq 0) {
    throw 'The database password cannot be empty. Run this script again and enter the generated password.'
}

$pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($securePassword)
try {
    $dbPassword = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($pointer)
    [Environment]::SetEnvironmentVariable('DB_PASSWORD', $dbPassword, 'User')
    $env:DB_PASSWORD = $dbPassword
}
finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($pointer)
    $dbPassword = $null
    $securePassword.Dispose()
}

# Generate a new 256-bit random HMAC secret and store it as Base64.
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try {
    $secretBytes = New-Object byte[] 48
    $rng.GetBytes($secretBytes)
    $jwtSecret = [Convert]::ToBase64String($secretBytes)
}
finally {
    $rng.Dispose()
}

[Environment]::SetEnvironmentVariable('JWT_SECRET', $jwtSecret, 'User')
$env:JWT_SECRET = $jwtSecret
[Environment]::SetEnvironmentVariable('JWT_EXPIRATION', '86400000', 'User')
$env:JWT_EXPIRATION = '86400000'
[Environment]::SetEnvironmentVariable('FILE_UPLOAD_DIR', 'uploads', 'User')
$env:FILE_UPLOAD_DIR = 'uploads'

# Clear local script references; the secret remains only in the process/user environment.
$jwtSecret = $null
$secretBytes = $null

Write-Host ""
Write-Host 'Configuration saved.' -ForegroundColor Green
Write-Host 'DB_URL: set (localhost:3306/voice_clone_db)'
Write-Host 'DB_USERNAME: set (voiceclone_app)'
Write-Host 'DB_PASSWORD: set (hidden)'
Write-Host 'JWT_SECRET: generated and saved (hidden)'
Write-Host 'JWT_EXPIRATION: 86400000 ms (24 hours)'
Write-Host ""
Write-Host 'Run Spring Boot from this same terminal using .\mvnw.cmd spring-boot:run.' -ForegroundColor Yellow
Write-Host 'Existing JWT tokens will stop working because the JWT signing secret changed. Users must log in again.'
